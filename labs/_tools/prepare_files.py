# ------------------------------------------------------------------ writing helpers
def write_text(rel: str, text: str) -> None:
    path = OUT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((text.strip() + "\n").encode("utf-8"))


def sheet(wb, title, header, rows, fill_cols=(), widths=None, validations=None):
    ws = wb.create_sheet(title)
    ws.sheet_view.rightToLeft = True
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = HEAD_FILL
        c.alignment = Alignment(wrap_text=True, vertical="top")
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
            if c.column - 1 in fill_cols:
                c.fill = FILL_FILL
    for i, w in enumerate(widths or [18] * len(header)):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i + 1)].width = w
    ws.freeze_panes = "A2"
    for col, values in (validations or {}).items():
        inline = '"' + ",".join(values) + '"'
        if len(inline) > 250:  # Excel refuses an inline list longer than 255 characters: use a hidden sheet
            if "lists" not in wb.sheetnames:
                wb.create_sheet("lists").sheet_state = "hidden"
            lw = wb["lists"]
            lc = lw.max_column + 1 if lw.max_row > 1 or lw["A1"].value else 1
            for i, v in enumerate(values):
                lw.cell(row=i + 1, column=lc, value=v)
            letter = openpyxl.utils.get_column_letter(lc)
            inline = f"lists!${letter}$1:${letter}${len(values)}"
        dv = DataValidation(type="list", formula1=inline, allow_blank=True)
        ws.add_data_validation(dv)
        dv.add(f"{col}2:{col}{max(2, len(rows) + 1)}")
    return ws


def save(wb, rel: str) -> None:
    del wb[wb.sheetnames[0]]
    wb.properties.creator = AGENCY
    wb.properties.lastModifiedBy = AGENCY
    wb.properties.created = wb.properties.modified = FIXED
    path = OUT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    wb.save(tmp)
    # rewrite the zip with fixed times and a fixed order, so the bytes never change
    with zipfile.ZipFile(tmp) as z:
        items = [(i.filename, z.read(i.filename)) for i in z.infolist()]
    # openpyxl stamps the save time into the core properties: put the fixed time back
    stamp = FIXED.strftime("%Y-%m-%dT%H:%M:%SZ").encode()
    items = [(n, re.sub(rb"(<dcterms:(?:created|modified)[^>]*>)[^<]*(</dcterms)", rb"\g<1>" + stamp + rb"\g<2>", d))
             if n == "docProps/core.xml" else (n, d) for n, d in items]
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in items:
            info = zipfile.ZipInfo(name, date_time=FIXED.timetuple()[:6])
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, data)
    tmp.unlink()


def new_wb():
    return openpyxl.Workbook()


def put_ref(name: str, data) -> None:
    REF.mkdir(parents=True, exist_ok=True)
    (REF / name).write_bytes((json.dumps(data, ensure_ascii=False, indent=1) + "\n").encode("utf-8"))


